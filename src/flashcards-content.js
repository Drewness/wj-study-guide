export function getFlashcards(rank) {
  return getQuestionPool(rank, ["vocabulary"]).map((question) => {
    const term = question.prompt.replace("Complete the vocabulary pair: ", "");
    const reversed = reversedRows.has(question.id);
    return {
      id: question.id,
      english: reversed ? question.answer : term,
      japanese: reversed ? term : question.answer,
      rank: question.rankTitle,
      page: question.page,
      sourceNote: question.sourceNote,
    };
  });
}

export function shuffleFlashcards(cards, random = Math.random) {
  const shuffled = [...cards];
  for (let index = shuffled.length - 1; index > 0; index--) {
    const other = Math.floor(random() * (index + 1));
    [shuffled[index], shuffled[other]] = [shuffled[other], shuffled[index]];
  }
  return shuffled;
}
